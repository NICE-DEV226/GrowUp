export type TranslationKey = keyof typeof translations.fr;
export type LanguageCode = 'fr' | 'en' | 'es';

// Fonction helper pour obtenir la traduction
export const getTranslation = (key: TranslationKey, lang: string): string => {
  const languageCode = lang === 'Français' ? 'fr' : lang === 'English' ? 'en' : lang === 'Español' ? 'es' : 'fr';
  return translations[languageCode][key] || translations.fr[key];
};
